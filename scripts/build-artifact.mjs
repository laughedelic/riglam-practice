#!/usr/bin/env node
// Builds the artifact: dist/artifact/index.html, one self-contained page in the shape the Claude Artifact
// tool publishes (an HTML fragment: <title> and font links, <style>, markup, one <script>; the tool adds the
// document skeleton). Publish it with the Artifact tool; see docs/ARTIFACT-LOOP.md.
import { build } from "vite";
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { execSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import config from "../vite.artifact.config.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const out = resolve(root, "dist/artifact");
const parts = resolve(out, ".parts");

try {
  await build(config);
} catch (e) {
  // the usual failure is a missing data key (scripts/vite-full-data.mjs): say that in one line instead of a stack trace
  const key = /needs the data key[^\n]*/.exec(String(e?.message ?? e));
  console.error(key ? `build:artifact failed: ${key[0]}` : e);
  process.exit(1);
}

const read = (p) => readFileSync(resolve(parts, p), "utf8");
const js = read("app.js").trim();
const css = read("app.css").trim();
let head = readFileSync(resolve(root, "src/artifact/head.html"), "utf8").trim();
// ARTIFACT_TITLE renames the page, so a trial build can be published next to the real artifact without being mistaken for it.
if (process.env.ARTIFACT_TITLE) head = head.replace(/<title>[^<]*<\/title>/, `<title>${process.env.ARTIFACT_TITLE.replace(/[<>&]/g, "")}</title>`);
const markup = readFileSync(resolve(root, "src/app/markup.html"), "utf8").trim();

// Text inlined into <script> and <style> must not contain their closing tags or an HTML comment opener.
if (/<\/script/i.test(js) || /<!--/.test(js)) throw new Error("the bundled script contains </script or <!-- and cannot be inlined");
if (/<\/style/i.test(css)) throw new Error("the bundled stylesheet contains </style and cannot be inlined");

let sha = "unknown";
try { sha = execSync("git rev-parse --short HEAD", { cwd: root, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch { /* not a git checkout */ }

const page = `<!-- riglam-practice ${pkg.version} (${sha}), artifact build. Generated by scripts/build-artifact.mjs; edit the sources in src/. -->
${head}
<style>
${css}
</style>

${markup}

<script>
${js}
</script>
`;

mkdirSync(out, { recursive: true });
writeFileSync(resolve(out, "index.html"), page);
rmSync(parts, { recursive: true, force: true });
console.log(`dist/artifact/index.html  ${(page.length / 1024).toFixed(0)} KiB (script ${(js.length / 1024).toFixed(0)}, style ${(css.length / 1024).toFixed(0)})`);
