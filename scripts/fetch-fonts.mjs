#!/usr/bin/env node
// Downloads the Google Fonts the page asks for (the stylesheet link in src/artifact/head.html) and writes them
// as local files, so the installed app renders with the same faces as the artifact and works offline.
// Output: src/pwa/fonts/*.woff2 and src/pwa/fonts.css. Run `npm run fonts` when the link in head.html changes.
// Only the subsets the content needs are kept; the others fall back to the system font.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const KEEP = new Set(["latin", "latin-ext", "cyrillic", "cyrillic-ext", "math", "symbols", "full"]); // "full": a face Google serves without subsets (Noto Sans Math)
const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/147.0.0.0 Safari/537.36";

const head = readFileSync(resolve(root, "src/artifact/head.html"), "utf8");
const link = head.match(/href="(https:\/\/fonts\.googleapis\.com\/css2[^"]+)"/)?.[1]?.replaceAll("&amp;", "&");
if (!link) throw new Error("no Google Fonts stylesheet link in src/artifact/head.html");

const css = await (await fetch(link, { headers: { "user-agent": UA } })).text();
const faces = [...css.matchAll(/(?:\/\*\s*([\w-]+)\s*\*\/\s*)?@font-face\s*\{([^}]+)\}/g)].map((m) => ({ subset: m[1] ?? "full", body: m[2] }));
if (!faces.length) throw new Error("the stylesheet had no @font-face rules");

const outDir = resolve(root, "src/pwa/fonts");
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const files = new Map(); // remote url -> local name
let out = "/* Generated by scripts/fetch-fonts.mjs from the Google Fonts stylesheet in src/artifact/head.html. Do not edit. */\n";
for (const { subset, body } of faces) {
  if (!KEEP.has(subset)) continue;
  const url = body.match(/url\((https:[^)]+)\)/)[1];
  if (!files.has(url)) {
    const buf = Buffer.from(await (await fetch(url, { headers: { "user-agent": UA } })).arrayBuffer());
    const family = body.match(/font-family:\s*'([^']+)'/)[1].toLowerCase().replaceAll(" ", "-");
    const name = `${family}-${subset}-${createHash("sha1").update(buf).digest("hex").slice(0, 8)}.woff2`;
    writeFileSync(resolve(outDir, name), buf);
    files.set(url, name);
  }
  out += `@font-face{${body.replace(url, "./fonts/" + files.get(url)).replace(/\s+/g, " ").trim()}}\n`;
}
writeFileSync(resolve(root, "src/pwa/fonts.css"), out);
console.log(`${files.size} font files, ${faces.length} faces in the stylesheet, ${out.split("\n").length - 2} kept`);
